/* parser-hdfc.js -- HDFC Bank statement parser (single file, standalone).
   Structure it relies on (verified on HDFC "Statement of account" PDFs as read by the browser):
     - a transaction starts on a line beginning with dd/mm/yy; its amounts are on that same line:
         date | narration (first line) | chq/ref no | value date | withdrawal | deposit | closing balance
     - narration continues on the following lines until the next transaction
     - each page prints an account block (Page No, Account Branch, OD Limit ...) that is NOT part of any narration
     - the statement summary (Opening Balance, Dr Count, Cr Count, Debits, Credits, Closing) is printed at the end
   Direction (Dr/Cr) comes from the running balance; the printed opening balance starts the chain.
   Registers itself with the tool: bank id 7 (HDFC Bank Ltd) or the statement text. */
(function (root) {
  'use strict';
  var Core = (typeof module !== 'undefined' && module.exports) ? require('../bank-parser-core.js') : root.BankParserCore;

  var DATE_START = /^(\d{2})\/(\d{2})\/(\d{2})\s+(.*)$/;
  var MONEY = /^\d{1,3}(?:,\d{2,3})*\.\d{2}$|^\d+\.\d{2}$/;
  var FURNITURE = [
    /^Page No/i, /HDFC BANK LIMITED/i, /^\*Closing balance/i, /^Contents of this statement/i, /^this statement\.?$/i,
    /^State account branch/i, /^HDFC Bank GSTIN/i, /^Registered Office Address/i, /^M\/S\./i,
    /City\s*:/i, /Account Branch\s*:/i, /^Address\s*:/i, /^FP153/i, /^MEMCO ROAD/i, /OD Limit\s*:/i, /Currency\s*:/i,
    /Email\s*:/i, /Cust ID\s*:/i, /Account No\s*:/i, /A\/C Open Date/i, /Account Status\s*:/i, /RTGS\/NEFT IFSC/i,
    /Branch Code\s*:/i, /Phone no/i, /Product Code\s*:/i, /^Nomination/i, /JOINT HOLDERS/i, /^From\s*:/i,
    /Statement of account/i, /^Date\s+Narration/i, /^18-B SHARDA/i, /^NR PICKERS/i, /^SARASPUR/i,
    /^AHMEDABAD 380018/i, /^GUJARAT INDIA/i, /^Generated On/i, /Generated By/i, /Requesting Branch/i,
    /computer generated statement/i, /not require signature/i, /^\d{9,}$/
  ];
  function isFurniture(line) { for (var i = 0; i < FURNITURE.length; i++) if (FURNITURE[i].test(line)) return true; return false; }
  function num(s) { return parseFloat(String(s).replace(/,/g, '')); }
  function ymd(d, m, y) { return '20' + y + m + d; }

  function openingFromSummary(lines) {
    var out = { opening: null, debit: null, credit: null, closing: null };
    for (var i = 0; i < lines.length; i++) {
      if (/^Opening Balance/i.test(lines[i]) && /Debits/i.test(lines[i])) {
        for (var j = i + 1; j < Math.min(lines.length, i + 3); j++) {
          var toks = lines[j].split(/\s+/), dec = toks.filter(function (t) { return MONEY.test(t); });
          if (dec.length >= 4) { out.opening = num(dec[0]); out.debit = num(dec[dec.length - 3]); out.credit = num(dec[dec.length - 2]); out.closing = num(dec[dec.length - 1]); break; }
        }
        break;
      }
    }
    return out;
  }

  function parse(text) {
    var raw = String(text || '').split(/\r?\n/).map(function (l) { return l.replace(/\s+/g, ' ').trim(); });
    var summary = openingFromSummary(raw);
    // rows: stop at the summary block
    var end = raw.length;
    for (var s = 0; s < raw.length; s++) if (/STATEMENT SUMMARY/i.test(raw[s])) { end = s; break; }

    var rows = [], cur = null, skipped = [];
    function closeRow() { if (cur) { rows.push(cur); cur = null; } }
    for (var i = 0; i < end; i++) {
      var line = raw[i];
      if (!line) continue;
      var m = line.match(DATE_START);
      if (m) {
        closeRow();
        var rest = m[4], toks = rest.split(' ');
        // value date = the second dd/mm/yy on the line; amounts follow it
        var vIdx = -1;
        for (var k = 0; k < toks.length; k++) if (/^\d{2}\/\d{2}\/\d{2}$/.test(toks[k])) { vIdx = k; break; }
        if (vIdx < 0) { skipped.push({ lines: [line], reason: 'no value date' }); continue; }
        var after = toks.slice(vIdx + 1).filter(function (t) { return t !== ''; });
        var amounts = after.filter(function (t) { return MONEY.test(t); });
        if (amounts.length < 2) { skipped.push({ lines: [line], reason: 'amount/balance missing on the transaction line' }); continue; }
        var before = toks.slice(0, vIdx);
        var refNo = before.length > 1 && /\d/.test(before[before.length - 1]) && before[before.length - 1].length >= 6 ? before[before.length - 1] : '';
        var narr = (refNo ? before.slice(0, -1) : before).join(' ');
        cur = {
          date: ymd(m[1], m[2], m[3]), narration: narr, refNo: refNo,
          amount: num(amounts[0]), balance: num(amounts[amounts.length - 1]), lines: 1
        };
        continue;
      }
      if (!cur) { skipped.push({ lines: [line], reason: 'text before first transaction' }); continue; }
      if (isFurniture(line)) continue;                      // page furniture never belongs to a narration
      cur.narration += ' ' + line; cur.lines++;
    }
    closeRow();

    // direction and checks from the running balance (the printed opening starts the chain)
    var prev = summary.opening, dr = 0, cr = 0, transactions = [];
    rows.forEach(function (r, idx) {
      var conf = 'high', drCr = null;
      if (prev !== null) {
        var d = Math.round((r.balance - prev) * 100) / 100;
        if (Math.abs(Math.abs(d) - r.amount) < 0.005) drCr = d > 0 ? 'C' : 'D';
        else { conf = 'low'; drCr = d > 0 ? 'C' : 'D'; }
      } else { conf = 'low'; }
      prev = r.balance;
      var narration = r.narration.replace(/\s+/g, ' ').replace(/^[-\s]+|[-\s]+$/g, '').trim();
      transactions.push({ date: r.date, narration: narration || '(narration not detected)', amount: Math.round(r.amount * 100) / 100,
        drCr: drCr || 'D', refNo: r.refNo, balance: r.balance, confidence: conf, reference_no: 'HDFC-' + (idx + 1) });
      if (drCr === 'C') cr += r.amount; else dr += r.amount;
    });

    var dates = transactions.map(function (t) { return t.date; }).sort();
    var statement = {
      opening_balance: summary.opening, closing_balance: summary.closing,
      period_start: dates[0] || null, period_end: dates[dates.length - 1] || null,
      opening_source: summary.opening !== null ? 'statement' : 'none',
      closing_source: summary.closing !== null ? 'statement' : 'none',
      printed_total_debit: summary.debit, printed_total_credit: summary.credit,
      totals_match: summary.debit !== null ? Math.abs(Math.round(dr * 100) / 100 - summary.debit) < 0.05 && Math.abs(Math.round(cr * 100) / 100 - summary.credit) < 0.05 : null
    };
    return {
      transactions: transactions, skipped: skipped, statement: statement, layout: 'hdfc', directionFromMarker: false,
      repair: { reconstructed: 0, noBalanceEffect: 0, amountFromBalance: 0, markerConflicts: 0, headGap: 0, tailGap: 0, firstDirection: null,
        notes: summary.opening === null ? ['The opening balance was not found on the statement.'] : [] }
    };
  }

  parse.wantsHints = false;
  parse.meta = {
    key: 'hdfc', label: 'HDFC Bank', bankIds: ['7'],
    detect: function (t) { return /HDFC\s*BANK/i.test(t) && /Statement\s*of\s*account/i.test(t) && /HDFC0\d{6}/i.test(t); }
  };
  Core.registerParser(parse.meta.key, parse, parse.meta);
  if (typeof module !== 'undefined' && module.exports) module.exports = parse;
})(typeof window !== 'undefined' ? window : this);
